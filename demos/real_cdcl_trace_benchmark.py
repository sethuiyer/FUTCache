#!/usr/bin/env python3
"""Executing CDCL conflict-trace benchmark for backjump-depth predictability.

This benchmark runs an instrumented CDCL engine on generated SAT benchmark instances.
The input formulas are generated by the repository's SAT-family generators; the learned
clauses are not synthetic labels or manufactured resolvents: they are produced endogenously
by active CDCL search using 1-UIP analysis, two-watched-literal BCP, VSIDS-style activity,
Luby restarts, asserting learned clauses, and implication-trail backtracking.

Zero-leakage protocol:
  1. b(C) is never present in a feature vector or partition.
  2. Ablation A uses structural geometry only: no b(C), no LBD.
  3. LBD-only baseline measures what LBD alone predicts.
  4. Ablation B combines structural geometry with LBD, still without b(C).
  5. Epsilon is fixed in code: 0.25 for A and 0.30 for LBD/B.
  6. Significance is measured with matched-pair permutation tests: FUTCache's exact
     representative links stay frozen while backjump labels are shuffled.
  7. Degenerate target distributions are flagged and excluded from the cross-family
     predictive-evidence summary.
"""

