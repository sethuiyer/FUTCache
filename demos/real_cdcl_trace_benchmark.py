@dataclass
class RealConflictClause:
    id: int
    lits: List[int]
    lbd: int
    backjump_level: int
    activity: float


def luby(i: int) -> int:
    """Standard Luby sequence, indexed from 1."""
    k = 1
    while True:
        if i == (1 << k) - 1:
            return 1 << (k - 1)
        if (1 << (k - 1)) <= i < (1 << k) - 1:
            return luby(i - (1 << (k - 1)) + 1)
        k += 1


class InstrumentedCDCL:
    """Small executing CDCL engine used only to generate endogenous conflict traces."""

    def __init__(self, num_vars: int, clauses: List[List[int]]):
        self.num_vars = num_vars
        self.assignment: Dict[int, bool] = {}
        self.decision_level: Dict[int, int] = {}
        self.reason: Dict[int, Optional[int]] = {}
        self.trail: List[int] = []
        self.trail_lim: List[int] = []
        self.qhead = 0

        self.clauses: List[List[int]] = [list(c) for c in clauses]
        self.watches: Dict[int, List[int]] = defaultdict(list)
        for idx, c in enumerate(self.clauses):
            if len(c) >= 2:
                self.watches[c[0]].append(idx)
                self.watches[c[1]].append(idx)

        self.var_activity: Dict[int, float] = defaultdict(float)
        self.var_inc = 1.0
        self.var_decay = 0.95

        self.conflicts = 0
        self.restarts = 0
        self.restart_base = 32
        self.restart_limit = self.restart_base * luby(1)
        self.conflicts_since_restart = 0
        self.conflict_trace: List[RealConflictClause] = []

    def lit_val(self, lit: int) -> Optional[bool]:
        v = abs(lit)
        if v not in self.assignment:
            return None
        val = self.assignment[v]
        return val if lit > 0 else not val

    def current_level(self) -> int:
        return len(self.trail_lim)

    def assign(self, lit: int, reason_idx: Optional[int] = None) -> bool:
        v = abs(lit)
        val = lit > 0
        if v in self.assignment:
            return self.assignment[v] == val
        self.assignment[v] = val
        self.decision_level[v] = self.current_level()
        self.reason[v] = reason_idx
        self.trail.append(lit)
        return True

    def bcp(self) -> Optional[int]:
        while self.qhead < len(self.trail):
            p = self.trail[self.qhead]
            self.qhead += 1
            false_lit = -p
            watch_list = list(self.watches[false_lit])
            self.watches[false_lit] = []

            for i, c_idx in enumerate(watch_list):
                if c_idx >= len(self.clauses):
                    continue
                c = self.clauses[c_idx]
                if len(c) < 2:
                    continue

                if c[0] == false_lit:
                    c[0], c[1] = c[1], c[0]

                if self.lit_val(c[0]) is True:
                    self.watches[false_lit].append(c_idx)
                    continue

                found_new_watch = False
                for k in range(2, len(c)):
                    if self.lit_val(c[k]) is not False:
                        c[1], c[k] = c[k], c[1]
                        self.watches[c[1]].append(c_idx)
                        found_new_watch = True
                        break

                if found_new_watch:
                    continue

                self.watches[false_lit].append(c_idx)
                first_val = self.lit_val(c[0])
                if first_val is False:
                    for rem in watch_list[i + 1 :]:
                        self.watches[false_lit].append(rem)
                    return c_idx
                if first_val is None:
                    self.assign(c[0], reason_idx=c_idx)

        return None

    def analyze_conflict(self, conflict_c_idx: int) -> Tuple[List[int], int, int]:
        """Derive an asserting 1-UIP learned clause and its LBD/backjump level."""
        learned_tail: List[int] = []
        seen = set()
        path_count = 0
        p: Optional[int] = None
        c_idx: Optional[int] = conflict_c_idx
        curr_level = self.current_level()
        idx = len(self.trail) - 1

        while True:
            if c_idx is not None:
                for lit in self.clauses[c_idx]:
                    v = abs(lit)
                    if p is not None and v == abs(p):
                        continue
                    if v in seen or self.decision_level.get(v, 0) <= 0:
                        continue
                    seen.add(v)
                    self.var_activity[v] += self.var_inc
                    if self.decision_level[v] == curr_level:
                        path_count += 1
                    else:
                        learned_tail.append(lit)

            while idx >= 0:
                p = self.trail[idx]
                idx -= 1
                if abs(p) in seen:
                    break

            if p is None or abs(p) not in seen:
                break

            seen.discard(abs(p))
            path_count -= 1
            if path_count <= 0:
                break
            c_idx = self.reason.get(abs(p))

        # Put the asserting UIP literal first. This matters after backtracking:
        # learned[0] must become unit and is enqueued with this learned clause as reason.
        learned = [-p] + learned_tail if p is not None else learned_tail

        levels = [self.decision_level.get(abs(lit), 0) for lit in learned]
        lbd = len(set(levels))
        backjump_level = max(levels[1:], default=0)
        return learned, lbd, backjump_level

    def backtrack_to(self, level: int):
        if self.current_level() <= level:
            return
        while len(self.trail_lim) > level:
            lim = self.trail_lim.pop()
            while len(self.trail) > lim:
                p = self.trail.pop()
                v = abs(p)
                self.assignment.pop(v, None)
                self.decision_level.pop(v, None)
                self.reason.pop(v, None)
        self.qhead = len(self.trail)

    def pick_branch_lit(self) -> Optional[int]:
        unassigned = [v for v in range(1, self.num_vars + 1) if v not in self.assignment]
        if not unassigned:
            return None
        return max(unassigned, key=lambda v: self.var_activity[v])

    def restart(self):
        self.backtrack_to(0)
        self.restarts += 1
        self.conflicts_since_restart = 0
        self.restart_limit = self.restart_base * luby(self.restarts + 1)

    def collect_conflicts(self, target_conflicts: int = 1500) -> List[RealConflictClause]:
        if self.bcp() is not None:
            return self.conflict_trace

        while self.conflicts < target_conflicts:
            if self.conflicts_since_restart >= self.restart_limit:
                self.restart()

            next_lit = self.pick_branch_lit()
            if next_lit is None:
                break

            self.trail_lim.append(len(self.trail))
            self.assign(next_lit)

            while True:
                confl = self.bcp()
                if confl is None:
                    break

                self.conflicts += 1
                self.conflicts_since_restart += 1
                if self.current_level() == 0:
                    return self.conflict_trace

                learned_lits, lbd, backjump_level = self.analyze_conflict(confl)
                self.conflict_trace.append(
                    RealConflictClause(
                        id=self.conflicts,
                        lits=list(learned_lits),
                        lbd=lbd,
                        backjump_level=backjump_level,
                        activity=float(
                            sum(self.var_activity[abs(x)] for x in learned_lits)
                            / max(len(learned_lits), 1)
                        ),
                    )
                )

                if self.conflicts >= target_conflicts:
                    return self.conflict_trace

                self.backtrack_to(backjump_level)
                new_idx = len(self.clauses)
                self.clauses.append(list(learned_lits))

                if len(learned_lits) >= 2:
                    self.watches[learned_lits[0]].append(new_idx)
                    self.watches[learned_lits[1]].append(new_idx)
                # Assert the learned 1-UIP literal at the backjump level.
                if learned_lits:
                    if not self.assign(learned_lits[0], reason_idx=new_idx):
                        raise RuntimeError("asserting learned literal contradicts trail after backjump")

                self.var_inc *= 1.0 / self.var_decay

        return self.conflict_trace


def _structural_parts(clause: RealConflictClause, total_vars: int):
    lits = clause.lits
    pos_count = sum(1 for x in lits if x > 0)
    pos_ratio = pos_count / max(len(lits), 1)
    length = float(len(lits))
    var_ids = [abs(x) for x in lits]
    var_span = (
        float(max(var_ids) - min(var_ids)) / float(max(total_vars, 1)) if var_ids else 0.0
    )
    min_id = float(min(var_ids)) / float(max(total_vars, 1)) if var_ids else 0.0
    hash_sig = (
        float(sum((v * 2654435761) % 1000 for v in var_ids) % 100) / 100.0
        if var_ids
        else 0.0
    )
    ratio_bucket = int(pos_ratio * 4)
    size_bucket = min(len(lits), 8)
    return pos_ratio, length, var_span, min_id, hash_sig, ratio_bucket, size_bucket


def extract_ablation_a(clause: RealConflictClause, total_vars: int) -> Tuple[str, np.ndarray]:
    """Pure structural geometry: NO backjump and NO LBD."""
    pos_ratio, length, var_span, min_id, hash_sig, ratio_bucket, size_bucket = _structural_parts(
        clause, total_vars
    )
    p_key = f"P{ratio_bucket}_S{size_bucket}"
    vec = np.array(
        [length * 0.25, pos_ratio, var_span, min_id, hash_sig * 0.5], dtype=np.float64
    )
    return p_key, vec


def extract_lbd_only(clause: RealConflictClause, total_vars: int) -> Tuple[str, np.ndarray]:
    """LBD-only control: no structural geometry and no backjump target."""
    del total_vars
    return "ALL", np.array([float(clause.lbd) * 0.4, 0.0, 0.0, 0.0, 0.0], dtype=np.float64)


def extract_ablation_b(clause: RealConflictClause, total_vars: int) -> Tuple[str, np.ndarray]:
    """Structural geometry + LBD: NO backjump target."""
    _, length, var_span, min_id, hash_sig, ratio_bucket, size_bucket = _structural_parts(
        clause, total_vars
    )
    lbd_bucket = min(clause.lbd, 6)
    p_key = f"P{ratio_bucket}_S{size_bucket}_L{lbd_bucket}"
    vec = np.array(
        [float(clause.lbd) * 0.4, length * 0.25, var_span, min_id, hash_sig * 0.5],
        dtype=np.float64,
    )
    return p_key, vec


def evaluate_trace(trace: List[RealConflictClause], total_vars: int, extractor_fn, eps: float):
    caches: Dict[str, PackCache] = {}
    rep_clauses: Dict[str, Dict[int, RealConflictClause]] = defaultdict(dict)
    pairs: List[Tuple[int, int]] = []
    retained = 0

    for c in trace:
        p_key, vec = extractor_fn(c, total_vars)
        if p_key not in caches:
            caches[p_key] = PackCache(
                dimension=5,
                epsilon=eps,
                distance="l2",
                backend="vptree",
                domain_min=-1e4,
                domain_max=1e4,
            )

        res = caches[p_key].observe(vec)
        if res.is_novel:
            retained += 1
            rep_clauses[p_key][res.representative_id] = c
        else:
            rep = rep_clauses[p_key].get(res.representative_id)
            if rep is not None:
                pairs.append((c.id, rep.id))

    by_id = {c.id: c.backjump_level for c in trace}
    deltas = np.array([abs(by_id[a] - by_id[b]) for a, b in pairs], dtype=np.int64)
    p_exact = float(np.mean(deltas == 0)) if len(deltas) else 0.0
    p_close = float(np.mean(deltas <= 1)) if len(deltas) else 0.0
    mean_delta = float(np.mean(deltas)) if len(deltas) else 0.0
    return retained, pairs, p_exact, p_close, mean_delta


def matched_pair_permutation_test(
    trace: List[RealConflictClause],
    pairs: List[Tuple[int, int]],
    observed_exact: float,
    permutations: int = 1000,
    seed: int = 123,
):
    """Freeze FUTCache pair links; shuffle only b labels to get a valid null distribution."""
    if not pairs:
        return 0.0, 0.0, 1.0

    ids = np.array([c.id for c in trace], dtype=np.int64)
    labels = np.array([c.backjump_level for c in trace], dtype=np.int64)
    pos = {int(cid): i for i, cid in enumerate(ids)}
    left = np.array([pos[a] for a, _ in pairs], dtype=np.int64)
    right = np.array([pos[b] for _, b in pairs], dtype=np.int64)

    rng = np.random.default_rng(seed)
    null_exact = np.empty(permutations, dtype=np.float64)
    null_close = np.empty(permutations, dtype=np.float64)
    for i in range(permutations):
        shuffled = rng.permutation(labels)
        d = np.abs(shuffled[left] - shuffled[right])
        null_exact[i] = np.mean(d == 0)
        null_close[i] = np.mean(d <= 1)

    # Conservative one-sided Monte-Carlo p-value with +1 correction.
    p_value = (1.0 + float(np.sum(null_exact >= observed_exact))) / (permutations + 1.0)
    return float(np.mean(null_exact)), float(np.mean(null_close)), p_value


def wilson_interval(successes: int, n: int, z: float = 1.96) -> Tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = successes / n
    denom = 1.0 + z * z / n
    center = (p + z * z / (2.0 * n)) / denom
    radius = z * math.sqrt((p * (1.0 - p) + z * z / (4.0 * n)) / n) / denom
    return max(0.0, center - radius), min(1.0, center + radius)


def run_real_cdcl_benchmark():
    print("=" * 160)
    print("  EXECUTING CDCL CONFLICT-TRACE BENCHMARK: 1-UIP + 2WL BCP + VSIDS + LUBY RESTARTS")
    print("  Generated benchmark formulas; learned clauses and backjump depths arise from active solver search.")
    print("  Frozen eps: structural=0.25, LBD-only=0.30, structural+LBD=0.30; 1000 matched-pair permutations.")
    print("=" * 160)

    instances = [
        ("PHP(7, 6)", family_01_pigeonhole(7)),
        ("Random 3-SAT (N=60, Hard)", family_02_random_3sat(60, seed=42)),
        ("Random 4-SAT (N=35, Hard)", family_03_random_4sat(35, seed=42)),
        ("Graph 3-Coloring (N=45)", family_04_graph_coloring(45, p_edge=0.25, seed=42)),
        ("Tseitin Parity Graph (N=24)", family_06_tseitin_graph(24, seed=42)),
        ("Exact Cover X3C (N=45)", family_15_exact_cover_x3c(45, 60, seed=42)),
    ]

    print(
        f"{'Instance':<27} | {'1-UIPs':>6} | {'Marginal max':>12} | "
        f"{'Pure geom exact':>17} | {'Matched chance':>14} | {'p':>8} | "
        f"{'LBD-only':>9} | {'Geom+LBD':>10} | {'Status'}"
    )
    print("-" * 160)

    informative = 0
    geom_wins = 0

    for name, (_, n_vars, base_clauses) in instances:
        solver = InstrumentedCDCL(n_vars, base_clauses)
        trace = solver.collect_conflicts(target_conflicts=1500)
        n_trace = len(trace)
        if n_trace < 50:
            print(f"{name:<27} | {n_trace:>6} | solved before enough conflicts")
            continue

        labels = [c.backjump_level for c in trace]
        counts = Counter(labels)
        marginal_max = max(counts.values()) / n_trace
        degenerate = marginal_max >= 0.80

        reps_a, pairs_a, exact_a, close_a, delta_a = evaluate_trace(
            trace, n_vars, extract_ablation_a, eps=0.25
        )
        reps_l, pairs_l, exact_l, close_l, delta_l = evaluate_trace(
            trace, n_vars, extract_lbd_only, eps=0.30
        )
        reps_b, pairs_b, exact_b, close_b, delta_b = evaluate_trace(
            trace, n_vars, extract_ablation_b, eps=0.30
        )

        chance_a, chance_close_a, p_a = matched_pair_permutation_test(
            trace, pairs_a, exact_a, permutations=1000, seed=123
        )
        exact_successes = int(round(exact_a * len(pairs_a)))
        lo, hi = wilson_interval(exact_successes, len(pairs_a))

        if not degenerate:
            informative += 1
            if exact_a > chance_a and p_a <= 0.01:
                geom_wins += 1

        status = "DEGENERATE TARGET" if degenerate else "INFORMATIVE"
        print(
            f"{name:<27} | {n_trace:>6} | {marginal_max*100:>11.1f}% | "
            f"{exact_a*100:>6.1f}% [{lo*100:4.1f},{hi*100:4.1f}] | "
            f"{chance_a*100:>6.1f}% | {p_a:>8.4f} | "
            f"{exact_l*100:>8.1f}% | {exact_b*100:>9.1f}% | {status}"
        )
        print(
            f"  ↳ geom: reps={reps_a}, matched={len(pairs_a)}, within±1={close_a*100:.1f}%, meanΔ={delta_a:.2f}; "
            f"null within±1={chance_close_a*100:.1f}% | "
            f"LBD-only within±1={close_l*100:.1f}% meanΔ={delta_l:.2f} | "
            f"Geom+LBD within±1={close_b*100:.1f}% meanΔ={delta_b:.2f}"
        )

    print("\n" + "=" * 160)
    print("  SCIENTIFIC SUMMARY")
    print("=" * 160)
    print("• Target leakage: none; b(C) is excluded from every feature vector and partition.")
    print("• Solver dynamics: learned clauses are endogenous asserting 1-UIP clauses from the executing CDCL engine.")
    print("• Inputs: SAT instances are generated benchmark-family formulas; the trace itself is not a fabricated resolvent stream.")
    print("• Controls: pure geometry is compared with matched-pair shuffled-label chance and an explicit LBD-only baseline.")
    print("• Degenerate targets: families with >=80% mass on one backjump level are flagged and excluded from evidence counts.")
    print(f"• Non-degenerate families with significant pure-geometry enrichment (p<=0.01): {geom_wins}/{informative}.")
    print("• Interpretation: when enrichment is significant, structural clause geometry predicts backjump behavior beyond the")
    print("  empirical marginal distribution and beyond a trivial label-frequency explanation.")
    print("=" * 160)


if __name__ == "__main__":
    run_real_cdcl_benchmark()
